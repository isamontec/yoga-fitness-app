------------------ DDL CLASES DE YOGA Y FITNESS ------------------

-- 1. TABLA PLAN MEMBRESIA
CREATE TABLE plan_membresia (
    p_id_plan            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    p_nombre_plan        VARCHAR2(100) NOT NULL,
    p_duracion_plan      NUMBER NOT NULL,
    p_fecha_inicio       DATE NOT NULL,
    p_fecha_finalizacion DATE NOT NULL,
    p_limite_clases      NUMBER NOT NULL,
    p_tipo_clase         VARCHAR2(50),
    p_precio             NUMBER(10, 2) NOT NULL,
    p_precio_descuento   NUMBER(10, 2),
    p_cantidad_planes    NUMBER NOT NULL,
    p_estado             VARCHAR2(20),
    CONSTRAINT pk_plan_membresia PRIMARY KEY (p_id_plan),
    CONSTRAINT chk_p_duracion CHECK (p_duracion_plan > 0),
    CONSTRAINT chk_p_tipo_clase CHECK (p_tipo_clase IN ('yoga', 'pilates', 'barre', 'multidisciplinario')),
    CONSTRAINT chk_p_precio CHECK (p_precio >= 0),
    CONSTRAINT chk_p_descuento CHECK (p_precio_descuento IS NULL OR p_precio_descuento < p_precio),
    CONSTRAINT chk_p_estado CHECK (p_estado IN ('activo', 'inactivo', 'agotado', 'disponible'))
);

-- 2. TABLA INSTRUCTOR
CREATE TABLE instructor (
    i_id_instructor            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    i_nombre_completo          VARCHAR2(150) NOT NULL,
    i_especialidad             VARCHAR2(50),
    i_tipo_contrato            VARCHAR2(50),
    i_cantidad_certificaciones NUMBER NOT NULL,
    i_tipo_certificacion       VARCHAR2(100),
    i_estado                   VARCHAR2(20),
    CONSTRAINT pk_instructor PRIMARY KEY (i_id_instructor),
    CONSTRAINT chk_i_especialidad CHECK (i_especialidad IN ('yoga', 'pilates', 'barre', 'multidisciplinario')),
    CONSTRAINT chk_i_tipo_contrato CHECK (i_tipo_contrato IN ('cátedra', 'medio tiempo', 'tiempo completo', 'tiempo indefinido')),
    CONSTRAINT chk_i_certificaciones CHECK (i_cantidad_certificaciones >= 1),
    CONSTRAINT chk_i_estado CHECK (i_estado IN ('activo', 'inactivo', 'en licencia', 'retirado', 'despedido'))
);

-- 3. TABLA CLASES
CREATE TABLE clases (
    c_id_clase        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    c_nombre_clase    VARCHAR2(100) NOT NULL,
    c_tipo_clase      VARCHAR2(50),
    c_dia             VARCHAR2(20),
    c_horario         VARCHAR2(20) NOT NULL,
    c_salon_clase     VARCHAR2(50) NOT NULL,
    c_cupo_max        NUMBER NOT NULL,
    c_intensidad      VARCHAR2(30),
    c_modalidad       VARCHAR2(30),
    c_estado          VARCHAR2(20),
    CONSTRAINT pk_clases PRIMARY KEY (c_id_clase),
    CONSTRAINT chk_c_tipo_clase CHECK (c_tipo_clase IN ('yoga', 'pilates', 'barre', 'multifuncional')),
    CONSTRAINT chk_c_dia CHECK (c_dia IN ('lunes', 'martes', 'miércoles', 'jueves', 'viernes', 'sabado')),
    CONSTRAINT chk_c_cupo_max CHECK (c_cupo_max > 0 AND c_cupo_max < 20),
    CONSTRAINT chk_c_intensidad CHECK (c_intensidad IN ('principiante', 'intermedio', 'avanzado', 'profesional')),
    CONSTRAINT chk_c_modalidad CHECK (c_modalidad IN ('reforma', 'mat', 'hot', 'normal')),
    CONSTRAINT chk_c_estado CHECK (c_estado IN ('programada', 'en curso', 'cancelada', 'reagendada', 'finalizada'))
);

-- 4. TABLA USUARIO
CREATE TABLE usuario (
    u_id_usuario           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    u_nombre_completo      VARCHAR2(150) NOT NULL,
    u_id_plan              NUMBER,
    u_genero               VARCHAR2(20),
    u_estado               VARCHAR2(20),
    u_direccion_residencia VARCHAR2(200),
    u_telefono             VARCHAR2(20) NOT NULL,
    u_correo_electronico   VARCHAR2(100) NOT NULL,
    u_condicion_medica     VARCHAR2(255),
    u_fecha_nacimiento     DATE NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (u_id_usuario),
    CONSTRAINT uk_u_correo UNIQUE (u_correo_electronico),
    CONSTRAINT chk_u_genero CHECK (u_genero IN ('femenino', 'masculino', 'otro')),
    CONSTRAINT chk_u_estado CHECK (u_estado IN ('activo', 'inactivo', 'cancelado'))
);

-- 5. TABLA KARDEX RESERVA
CREATE TABLE kardex_reserva (
    r_id_reserva         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    r_id_usuario         NUMBER NOT NULL,
    r_id_clase           NUMBER NOT NULL,
    r_id_instructor      NUMBER NOT NULL,
    r_id_plan            NUMBER NOT NULL,
    r_fecha_reserva      DATE NOT NULL,
    r_hora_reserva       VARCHAR2(20) NOT NULL,
    r_precio             NUMBER(10, 2),
    r_estado_asistencia  VARCHAR2(20),
    r_estado_reserva     VARCHAR2(20),
    CONSTRAINT pk_kardex_reserva PRIMARY KEY (r_id_reserva),
    CONSTRAINT chk_r_precio CHECK (r_precio >= 0),
    CONSTRAINT chk_r_asistencia CHECK (r_estado_asistencia IN ('asistió', 'no asistió', 'cancelado')),
    CONSTRAINT chk_r_reserva CHECK (r_estado_reserva IN ('confirmada', 'en espera', 'cancelada'))
);

-- 6. ASIGNACIÓN POSTERIOR DE CLAVES FORÁNEAS (RELACIONES)
ALTER TABLE usuario ADD CONSTRAINT fk_u_plan FOREIGN KEY (u_id_plan) REFERENCES plan_membresia (p_id_plan);
ALTER TABLE kardex_reserva ADD CONSTRAINT fk_r_usuario FOREIGN KEY (r_id_usuario) REFERENCES usuario (u_id_usuario);
ALTER TABLE kardex_reserva ADD CONSTRAINT fk_r_clase FOREIGN KEY (r_id_clase) REFERENCES clases (c_id_clase);
ALTER TABLE kardex_reserva ADD CONSTRAINT fk_r_instructor FOREIGN KEY (r_id_instructor) REFERENCES instructor (i_id_instructor);
ALTER TABLE kardex_reserva ADD CONSTRAINT fk_r_plan FOREIGN KEY (r_id_plan) REFERENCES plan_membresia (p_id_plan);